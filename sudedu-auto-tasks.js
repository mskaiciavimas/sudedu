    function curriculumCovered(grade, period) {
        const upTo = slotIndex(clamp(grade, 0, MAX_GRADE), period);
        const math = { ops: new Set(), ranges: new Set(), crossing: false, unknown: false, remainder: false, columns: false, table: null };
        const cats = new Set(), types = new Set();
        for (let i = 0; i <= upTo; i++) {
            const { grade: g, period: p } = slotOf(i);
            const raw = (typeof personalChlDict !== 'undefined' && personalChlDict[g] && personalChlDict[g][p] && personalChlDict[g][p].math) || [];
            raw.forEach(text => { const parsed = parseJson(text); if (Array.isArray(parsed) && Array.isArray(parsed[0]) && parsed[0][6] === 'C48') math.columns = true; });
            slotTasks(g, p, 'math').forEach(({ info }) => {
                if (info[1] === 'C7') (MIXED_OPS[info[2]] || []).forEach(o => math.ops.add(o));
                else (OP_NEEDS[info[1]] || []).forEach(o => math.ops.add(o));
                if (info[2] !== 'C18' && !MIXED_RANGE[info[2]]) math.ranges.add(info[2]);
                if (MIXED_RANGE[info[2]]) math.ranges.add(MIXED_RANGE[info[2]][0]);
                if (info[3] === 'C38') math.crossing = true;
                if (info[4] === 'C42') math.unknown = true;
                if (info[8] === true) math.remainder = true;
                if (info[2] === 'C18') {
                    const [a, b] = (info[7] || []).map(Number);
                    math.table = math.table ? [Math.min(math.table[0], a), Math.max(math.table[1], b)] : [a, b];
                }
            });
            slotTasks(g, p, 'grammar').forEach(({ info }) => Object.keys(info[4] || {}).forEach(k => cats.add(k)));
            slotTasks(g, p, 'text').forEach(({ info }) => types.add(info[2]));
        }
        return { math: { ...math, ops: [...math.ops], ranges: [...math.ranges] }, grammar: { cats: [...cats] }, text: { types: [...types] } };
    }

    // ---------------------------------------------------------------- what the results say
    // rows: { date, taskInfo, totalAnswers, mistakes, mistakesDetail } of the target's students; assigned: the task
    // settings ({ taskInfo }) of their tasks given and not done yet
    function statsOf(rows, today, assigned = []) {
        const st = { kinds: new Map(), subject: {}, table: new Map(), tableTotal: 0, cats: new Map(), pending: new Set() };
        assigned.forEach(a => { const info = parseJson(a.taskInfo); if (subjectOf(info)) st.pending.add(kindOf(normalizeInfo(info))); });
        SUBJECTS.forEach(s => { st.subject[s] = { answers: 0, mistakes: 0, perTask: [] }; });
        rows.forEach(row => {
            const info = parseJson(row.taskInfo);
            const subject = subjectOf(info);
            if (!subject) return;
            const age = daysBetween(row.date, today);
            if (age < 0 || age > PRACTICE_DAYS) return;
            const w = age <= RECENT_DAYS ? 1 : OLDER_WEIGHT;
            const answers = Number(row.totalAnswers) || 0, mistakes = Number(row.mistakes) || 0;
            const norm = normalizeInfo(info);
            const kind = kindOf(norm);
            if (!st.kinds.has(kind)) st.kinds.set(kind, { answers: 0, mistakes: 0, tasks: 0, lastAge: age, last: { answers: 0, mistakes: 0 } });
            const k = st.kinds.get(kind);
            k.answers += w * answers; k.mistakes += w * mistakes; k.tasks += 1;
            // (the latest day it was practised: all its tasks of that day together - for "recovered")
            if (age < k.lastAge) k.last = { answers: 0, mistakes: 0 };
            if (age <= k.lastAge) { k.last.answers += answers; k.last.mistakes += mistakes; }
            k.lastAge = Math.min(k.lastAge, age);
            const s = st.subject[subject];
            s.answers += w * answers; s.mistakes += w * mistakes; s.perTask.push(answers);
            const detail = Array.isArray(parseJson(row.mistakesDetail)) ? parseJson(row.mistakesDetail) : [];
            if (subject === 'math') {
                detail.forEach(d => {
                    if (!Array.isArray(d) || !Array.isArray(d[0]) || (d[1] !== 'M' && d[1] !== 'D')) return;
                    const a = Number(d[0][0]), b = Number(d[0][1]);
                    const tries = Array.isArray(d[2]) ? Math.max(1, Number(d[2][0]) || 1) : 1;
                    const nums = d[1] === 'M' ? [a, b] : [b, b ? a / b : 0];
                    if (!nums.every(n => Number.isInteger(n) && n >= 1 && n <= 10)) return;
                    const table = [...new Set(nums)].filter(n => n > 1);
                    table.forEach(n => st.table.set(n, (st.table.get(n) || 0) + w * tries / table.length));
                    if (table.length) st.tableTotal += w * tries;
                });
            } else if (subject === 'grammar') {
                // the questions split evenly between the task's categories; the mistakes by the category they were asked in
                const keys = Object.keys((norm[4] && typeof norm[4] === 'object') ? norm[4] : {});
                keys.forEach(c => { const e = st.cats.get(c) || { asked: 0, wrong: 0 }; e.asked += w * answers / keys.length; st.cats.set(c, e); });
                detail.forEach(item => {
                    if (!Array.isArray(item)) return;
                    const cat = String(item[1] || '').split('-')[0];
                    if (!/^C\d+$/.test(cat)) return;
                    const tries = Number(item[2] && item[2][0]) || 1;
                    const e = st.cats.get(cat) || { asked: 0, wrong: 0 };
                    e.wrong += w * tries;
                    st.cats.set(cat, e);
                });
            }
        });
        return st;
    }
    function typicalAnswers(st, subject) {
        return median(st.subject[subject].perTask.filter(x => x > 0)) || DEFAULT_TASK_ANSWERS;
    }
    // how a kind of task went for the target: { rate, average, index } - index > 1 = more mistakes than their average
    function problemOf(st, subject, kind) {
        const k = st.kinds.get(kind);
        const s = st.subject[subject];
        if (!k || !k.answers || !s.answers) return null;
        const average = s.mistakes / s.answers;
        const typical = typicalAnswers(st, subject);
        const smoothed = (k.mistakes + typical * average) / (k.answers + typical);
        const lastRate = k.last && k.last.answers ? k.last.mistakes / k.last.answers : null;
        return { rate: k.mistakes / k.answers, average, index: average > 0 ? smoothed / average : 1, mistakes: k.mistakes, answers: k.answers, lastAge: k.lastAge,
            lastRate, recovered: lastRate != null && lastRate <= average };
    }
    const isProblem = p => Boolean(p && p.mistakes > 0 && p.index > 1);
    const rateText = p => `${pct(p.rate)}% klaidų, vidutiniškai ${pct(p.average)}%`;
    // the multiplication table numbers holding at least half of the table mistakes, when they are next to each other
    function tableFocus(st) {
        if (st.tableTotal < 3) return null;
        const ranked = [...st.table.entries()].sort((x, y) => y[1] - x[1]);
        const chosen = [];
        let sum = 0;
        for (const [n, weight] of ranked) { chosen.push(n); sum += weight; if (sum >= st.tableTotal / 2) break; }
        const lo = Math.min(...chosen), hi = Math.max(...chosen);
        return hi - lo <= 3 ? { lo, hi, numbers: chosen.sort((x, y) => x - y) } : null;
    }
    // spelling categories with a larger share of the mistakes than of the questions (smoothed like the kinds)
    function grammarProblems(st, allowed) {
        const entries = [...st.cats.entries()].filter(([c]) => allowed.has(c));
        const asked = entries.reduce((s, [, e]) => s + e.asked, 0), wrong = entries.reduce((s, [, e]) => s + e.wrong, 0);
        if (!asked || !wrong) return [];
        const average = wrong / asked;
        const typical = typicalAnswers(st, 'grammar') / Math.max(1, entries.length);
        return entries
            .map(([code, e]) => ({ code, rate: e.asked ? e.wrong / e.asked : 0, wrong: e.wrong, index: ((e.wrong + typical * average) / (e.asked + typical)) / average }))
            .filter(x => x.wrong > 0 && x.index > 1)
            .sort((x, y) => y.index - x.index);
    }

    // ---------------------------------------------------------------- the candidates and the picks
    function catName(code) {
        const d = typeof parameterDictionary !== 'undefined' ? parameterDictionary[code] : null;
        return d && d.insightsListLabel ? d.insightsListLabel : code;
    }
    // the slot's covered tasks; nothing covered there: the closest slot with covered tasks (forward first)
    function currentPool(grade, period, subject, covered) {
        const home = slotIndex(grade, period);
        const take = index => {
            const { grade: g, period: p } = slotOf(index);
            const out = [];
            slotTasks(g, p, subject).forEach(({ info, duration }) => {
                const variant = coveredVariant(info, covered);
                if (variant && !out.some(x => x.id === JSON.stringify(variant))) out.push({ id: JSON.stringify(variant), info: variant, duration, kind: kindOf(variant), slot: index });
            });
            return out;
        };
        let items = take(home), from = home;
        for (let d = 1; !items.length && d < SLOT_COUNT; d++) {
            if (home + d < SLOT_COUNT && (items = take(home + d)).length) { from = home + d; break; }
            if (home - d >= 0 && (items = take(home - d)).length) { from = home - d; break; }
        }
        return { items, from, home };
    }
    function earlierProblems(grade, period, subject, covered, st, exclude) {
        const home = slotIndex(grade, period);
        const out = new Map();
        for (let i = home - 1; i >= 0; i--) {
            const { grade: g, period: p } = slotOf(i);
            slotTasks(g, p, subject).forEach(({ info, duration }) => {
                const variant = coveredVariant(info, covered);
                if (!variant) return;
                const kind = kindOf(variant);
                if (exclude.has(kind) || out.has(kind)) return;
                const problem = problemOf(st, subject, kind);
                // (recovered - the latest time with no more mistakes than usual: learnt again, not offered)
                if (isProblem(problem) && !problem.recovered) out.set(kind, { id: JSON.stringify(variant), info: variant, duration, kind, slot: i, problem });
            });
        }
        return [...out.values()].sort((a, b) => b.problem.index - a.problem.index || b.problem.mistakes - a.problem.mistakes);
    }
    const RECENT_PRACTICE_DAYS = 7;
    // a topic unit: math - the operation family (sudėtis / atimtis, daugyba / dalyba, įvairūs), number range, crossing,
    // equation and remainder (not which operation of the family or which number is unknown); text - type, class, level
    const OP_FAMILY = { C1: 'add', C2: 'add', C3: 'add', C4: 'mul', C5: 'mul', C6: 'mul', C7: 'mix' };
    function unitOf(info) {
        const subject = subjectOf(info);
        if (subject === 'math') return [OP_FAMILY[info[1]] || info[1], info[2], info[3] || '-', info[4], info[8] === true ? 'R' : '-'].join('|');
        if (subject === 'text') return [info[2], info[5], info[6]].join('|');
        return kindOf(info);
    }
    // how broad a kind is in its unit: both operations (sudėtis ir atimtis, daugyba ir dalyba) before one
    const breadthOf = info => (subjectOf(info) === 'math' && ['C3', 'C6', 'C7'].includes(info[1]) ? 2 : 1);
    // revision tasks of week w: a share of the subject's tasks over the weeks (a quarter: one a week - every fourth week)
    const revisionCount = (n, week, share = REVISION_SHARE) => Math.floor((week + 1) * n * share) - Math.floor(week * n * share);
    // a kind done in the last 7 days or given and not done yet goes after the others (the next week does not repeat it)
    function rotate(list, st) {
        const pendingOf = x => st.pending.has(x.kind) || x.unitPending;
        const ageOf = x => x.unitLastAge != null ? x.unitLastAge : (x.problem ? x.problem.lastAge : null);
        const recent = x => pendingOf(x) || (ageOf(x) != null && ageOf(x) <= RECENT_PRACTICE_DAYS);
        // (a kind given and not done yet: no note - the reason says enough)
        const note = x => pendingOf(x) ? '' : `spręsta prieš ${ageOf(x)} d.`;
        return [...list.filter(x => !recent(x)), ...list.filter(x => recent(x)).map(x => ({ ...x, recent: true, reason: note(x) ? `${x.reason} (${note(x)})` : x.reason }))];
    }
    // → { picks: [...n], ranked: [every candidate in the order it would be taken, with its reason] }
    function chooseTasks(target, subject, n, ctx) {
        const { grade, period } = target;
        const st = target.stats;
        const pool = currentPool(grade, period, subject, ctx.covered);
        if (subject === 'grammar') return chooseGrammar(pool, n, st, ctx.covered, target, ctx.week || 0);
        const shifted = pool.from !== pool.home;
        const topic = shifted ? cap(pool.from > pool.home ? 'artimiausia išeita vėlesnio laikotarpio tema' : 'artimiausia išeita ankstesnio laikotarpio tema') : 'Šio laikotarpio tema';
        const current = pool.items.map(x => ({ ...x, unit: unitOf(x.info), problem: problemOf(st, subject, x.kind), difficulty: taskDifficulty(x.info, grade, period) }));
        // the topic units: their kinds, the broadest kind as the unit's own task
        const units = new Map();
        current.forEach(x => { if (!units.has(x.unit)) units.set(x.unit, []); units.get(x.unit).push(x); });
        const unitList = [...units.values()].map(kinds => {
            const rep = kinds.slice().sort((x, y) => breadthOf(y.info) - breadthOf(x.info) || (x.problem ? x.problem.answers : 0) - (y.problem ? y.problem.answers : 0) || x.difficulty - y.difficulty)[0];
            const tried = kinds.filter(x => x.problem);
            return { rep, kinds, tried: tried.length > 0, lastAge: tried.length ? Math.min(...tried.map(x => x.problem.lastAge)) : null,
                pending: kinds.some(x => st.pending.has(x.kind)), difficulty: rep.difficulty };
        });
        // a) new units, easiest first
        const fresh = unitList.filter(u => !u.tried).sort((x, y) => x.difficulty - y.difficulty)
            .map(u => ({ ...u.rep, group: 'new', unitPending: u.pending, reason: shifted ? `${topic} – dar nespręsta` : 'Nauja šio laikotarpio tema – dar nespręsta' }));
        // b) the most problematic kinds, and the tried units - harder ones first, then the one done longest ago
        const weak = current.filter(x => isProblem(x.problem)).sort((x, y) => y.problem.index - x.problem.index)
            .map(x => ({ ...x, group: 'weak', reason: `${topic}, kurioje daugiausia klaidų (${rateText(x.problem)})` }));
        const settled = unitList.filter(u => u.tried).sort((x, y) => y.difficulty - x.difficulty || y.lastAge - x.lastAge)
            .map(u => ({ ...u.rep, problem: u.rep.problem || u.kinds.find(k => k.problem).problem, group: 'practised', unitLastAge: u.lastAge, unitPending: u.pending,
                reason: `${topic} – kartojimas (sunkesnės temos pirmiau; spręsta prieš ${u.lastAge} d.)` }));
        const tried = [];
        for (let i = 0; i < Math.max(weak.length, settled.length); i++) { if (weak[i]) tried.push(weak[i]); if (settled[i]) tried.push(settled[i]); }
        const currentOrder = rotate([...fresh, ...tried], st);
        const earlier = rotate(earlierProblems(grade, period, subject, ctx.covered, st, new Set(current.map(x => x.kind)))
            .map(x => ({ ...x, group: 'revision', difficulty: taskDifficulty(x.info, grade, period), reason: `Ankstesnio laikotarpio tema, kurioje daug klaidų (${rateText(x.problem)}; paskutinį kartą – ${pct(x.problem.lastRate)}%)` })), st);
        let revisions = Math.min(earlier.length, revisionCount(n, ctx.week || 0));
        if (!currentOrder.length) revisions = Math.min(earlier.length, n);
        const picks = [];
        // (a unit - or for revision a kind - once while others are left; then the order starts again)
        const takeFrom = (list, count) => {
            const used = new Set(picks.map(p => p.unit || p.kind));
            const fresh = list.filter(x => !used.has(x.unit || x.kind));
            const order = (fresh.length ? fresh : list).filter((x, i, all) => all.findIndex(y => (y.unit || y.kind) === (x.unit || x.kind)) === i);
            for (let i = 0; count > 0 && order.length; i++) { picks.push(order[i % order.length]); count--; }
        };
        takeFrom(earlier.slice(0, revisions), revisions);
        takeFrom(currentOrder, n - revisions);
        if (picks.length < n && earlier.length) takeFrom(earlier, n - picks.length);
        // the week: the current ones first in their order, the revision ones between them
        const ordered = interleave(picks.filter(p => p.group !== 'revision'), picks.filter(p => p.group === 'revision'));
        const focus = subject === 'math' ? tableFocus(st) : null;
        // the other choices (Keisti užduotį): the kinds of choice in turns - new, most mistakes, done longest ago,
        // earlier period - so each kind is near the top of the list
        const byGroup = ['new', 'weak', 'practised'].map(g => currentOrder.filter(x => x.group === g)).concat([earlier]);
        const ranked = [];
        for (let i = 0; byGroup.some(list => list.length > i); i++) byGroup.forEach(list => { if (list[i]) ranked.push(list[i]); });
        // (and every single kind of the units - e.g. atimtis alone - after them)
        current.forEach(x => { if (!ranked.some(r => r.kind === x.kind)) ranked.push({ ...x, group: x.problem ? 'practised' : 'new', reason: `${topic} (${x.problem ? `spręsta, ${pct(x.problem.rate)}% klaidų` : 'dar nespręsta'})` }); });
        return { picks: ordered.map((p, i) => finishMath(p, focus, ctx, target, subject, i)), ranked: ranked.map((p, i) => finishMath(p, focus, ctx, target, subject, 100 + i)) };
    }
    // the extra ones spread evenly between the main ones: 3 + 1 → main, extra, main, main
    function interleave(main, extra) {
        const total = main.length + extra.length;
        const at = new Set(extra.map((_, j) => Math.min(total - 1, Math.floor((j + 0.5) * total / extra.length))));
        const out = [];
        let m = 0, e = 0;
        for (let i = 0; i < total; i++) out.push(at.has(i) && e < extra.length ? extra[e++] : (m < main.length ? main[m++] : extra[e++]));
        return out;
    }
    const cap = s => s ? s[0].toUpperCase() + s.slice(1) : s;
    // a pick's final settings: the table numbers with the mistakes, the notation
    function finishMath(p, focus, ctx, target, subject, index) {
        if (subject !== 'math') return { ...p };
        let info = p.info.slice();
        let reason = p.reason;
        const coveredTable = ctx.covered.math && Array.isArray(ctx.covered.math.table) ? ctx.covered.math.table.map(Number) : null;
        // (only a table task picked for its mistakes: a new or practised one keeps all its numbers)
        if (focus && coveredTable && info[2] === 'C18' && info[8] !== true && (p.group === 'weak' || p.group === 'revision')) {
            const lo = Math.max(coveredTable[0], focus.lo), hi = Math.min(coveredTable[1], focus.hi);
            if (lo <= hi) { info[7] = [String(lo), String(hi)]; reason += `; lentelė su ${focus.numbers.join(', ')} – čia daugiausia klaidų`; }
        }
        info = withNotation(info, ctx.covered, `${ctx.seed}|${target.key}|${index}|${p.kind}`);
        return { ...p, info, id: JSON.stringify(info), reason };
    }
    function withNotation(info, covered, seed) {
        const copy = info.slice();
        const share = covered && covered.math && covered.math.columns && copy[4] !== 'C42' ? (COLUMN_SHARE[copy[2]] || 0) : 0;
        copy[6] = share > 0 && seededRandom(seed)() < share ? 'C48' : 'C47';
        return copy;
    }
    const GRAMMAR_CLASS_CATS = {
        C75: ['C61', 'C66', 'C67', 'C68', 'C85', 'C86', 'C87', 'C88', 'C89', 'C90', 'C91'],
        // (the one-task form's 3–4 grade rules: H – CH – F is a 1–2 grade one, PRIESAGOS (C70) is switched off there)
        C76: ['C62', 'C63', 'C64', 'C65', 'C66', 'C68', 'C69', 'C71', 'C72', 'C92']
    };
    function grammarWithCats(base, cats) {
        const info = base.info.slice();
        info[4] = Object.fromEntries(cats.slice().sort((x, y) => parseInt(x.slice(1)) - parseInt(y.slice(1))).map(c => [c, []]));
        return { ...base, info, id: JSON.stringify(info) };
    }
    function chooseGrammar(pool, n, st, covered, target, week) {
        if (!pool.items.length) return { picks: [], ranked: [] };
        const base = pool.items[0];
        const coveredCats = new Set((covered.grammar && covered.grammar.cats) || []);
        const allowed = new Set((GRAMMAR_CLASS_CATS[base.info[3]] || []).filter(c => coveredCats.has(c)).concat(Object.keys(base.info[4] || {})));
        const problems = grammarProblems(st, allowed);
        const full = { ...base, group: 'current', reason: `Šio laikotarpio rašybos taisyklės (${Object.keys(base.info[4]).length})` };
        const focusCats = problems.slice(0, 3);
        const focus = focusCats.length ? { ...grammarWithCats(base, focusCats.map(x => x.code)), group: 'weak',
            reason: `Taisyklės, kuriose daugiausia klaidų: ${focusCats.map(x => `${catName(x.code)} (${pct(x.rate)}%)`).join(', ')}` } : null;
        const focusCount = focus ? Math.min(n, revisionCount(n, week, GRAMMAR_FOCUS_SHARE)) : 0;
        const picks = interleave(Array.from({ length: n - focusCount }, () => full), Array.from({ length: focusCount }, () => focus));
        // other choices: every rule of the class level (always), all covered ones, each problematic category alone
        const level = base.info[3] === 'C75' ? '1–2' : '3–4';
        const ranked = [full];
        if (focus) ranked.push(focus);
        const allOfLevel = GRAMMAR_CLASS_CATS[base.info[3]] || [];
        if (allOfLevel.length) ranked.push({ ...grammarWithCats(base, allOfLevel), group: 'current', reason: `Visos ${level} klasės rašybos taisyklės (${allOfLevel.length})` });
        const allCovered = [...allowed];
        if (allCovered.length > Object.keys(base.info[4]).length && allCovered.length < allOfLevel.length) ranked.push({ ...grammarWithCats(base, allCovered), group: 'current', reason: `Visos išeitos ${level} klasės taisyklės (${allCovered.length})` });
        problems.slice(0, 5).forEach(x => ranked.push({ ...grammarWithCats(base, [x.code]), group: 'weak', reason: `Tik ${catName(x.code)} – ${pct(x.rate)}% klaidų` }));
        // (the same rules twice is one choice)
        const unique = ranked.filter((x, i) => ranked.findIndex(y => y.id === x.id) === i);
        return { picks, ranked: unique };
    }

    // ---------------------------------------------------------------- the week
    // the days the tasks go to: n tasks of each subject over the chosen days → [{ day, subject }]
    function scheduleWeek(counts, days) {
        const subjects = SUBJECTS.filter(s => counts[s] > 0);
        const total = subjects.reduce((s, x) => s + counts[x], 0);
        if (!total || !days.length) return [];
        const k = days.length;
        const loads = new Array(k).fill(0);
        if (total <= k) {
            for (let i = 0; i < total; i++) loads[Math.min(k - 1, Math.floor((i + 0.5) * k / total))] += 1;
        } else {
            const each = Math.floor(total / k), extra = total % k;
            loads.fill(each);
            for (let i = 0; i < extra; i++) loads[Math.min(k - 1, Math.floor((i + 0.5) * k / extra))] += 1;
        }
        const left = { ...counts };
        const lastDay = {};
        const out = [];
        loads.forEach((load, d) => {
            const today = new Set();
            for (let i = 0; i < load; i++) {
                const choice = subjects
                    .filter(s => left[s] > 0)
                    .sort((a, b) => (today.has(a) - today.has(b)) || (left[b] - left[a]) || ((lastDay[a] ?? -1) - (lastDay[b] ?? -1)) || subjects.indexOf(a) - subjects.indexOf(b))[0];
                if (!choice) break;
                left[choice] -= 1;
                today.add(choice);
                lastDay[choice] = d;
                out.push({ day: days[d], subject: choice });
            }
        });
        return out;
    }
